#!/usr/bin/env python3
"""Regenerate sonic_watch/sonic_sprites.h from the art files in assets/sonic_sprite/.

  sonic_big.txt  Sonic, in game and on the clock face (from the reference sheet
                 reference_29.webp; see build_big_from_reference.py for how the frames were made)

The file is plain text: a "= name" line starts each frame, then the rows ('#' lit, '.' dark),
Sonic facing right with his feet on the bottom row. Every frame has the same size; the order is
the SPR_* enum.
Optional: --preview out.png (needs Pillow).
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'assets', 'sonic_sprite')
OUT = os.path.join(ROOT, 'sonic_watch', 'sonic_sprites.h')

def load(fn):
    frames = []
    for line in open(os.path.join(ART, fn)):
        line = line.rstrip('\n')
        if line.startswith('='): frames.append((line[1:].strip(), []))
        elif frames and line.strip(): frames[-1][1].append(line.strip())
    H = len(frames[0][1]); W = len(frames[0][1][0])
    for name, rows in frames:
        if len(rows) != H or any(len(r) != W for r in rows): sys.exit('%s: frame %s must be %dx%d' % (fn, name, W, H))
    return frames, W, H

def emit(out, prefix, var, frames, W, H):
    RB = (W + 7) // 8
    out += ['static const uint8_t %s_W = %d;' % (prefix, W), 'static const uint8_t %s_H = %d;' % (prefix, H),
            'static const uint8_t %s_ROWBYTES = %d;' % (prefix, RB),
            'static const uint8_t %s[%d][%d] PROGMEM = {' % (var, len(frames), H * RB)]
    for name, rows in frames:
        out.append('  { // %s' % name)
        for r in rows:
            v = sum(1 << i for i, c in enumerate(r) if c == '#')
            out.append('    ' + ' '.join('0x%02X,' % ((v >> (8 * k)) & 255) for k in range(RB)) + '  // ' + r.replace('.', ' ').rstrip())
        out.append('  },')
    out.append('};')

big, BW, BH = load('sonic_big.txt')
out = ['#pragma once', '#include <Arduino.h>', '',
       '// GENERATED by scripts/gen_sonic_sprite.py from assets/sonic_sprite/ — edit the art there and',
       '// rerun. Facing right (mirrored for left), XBM bit order (LSB = leftmost pixel). Feet sit on',
       '// the bottom row; the spin-ball sits one row up (rolling radius is one smaller).']
emit(out, 'SONIC', 'sonicFrames', big, BW, BH)
out.append('enum : uint8_t {\n  ' + ', '.join('SPR_%s = %d' % (n.upper(), i) for i, (n, _) in enumerate(big)) + ',\n  SPR_COUNT = %d\n};' % len(big))
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote %s (%d frames, %dx%d)' % (OUT, len(big), BW, BH))

if '--preview' in sys.argv:
    from PIL import Image
    Z = 4
    img = Image.new('1', ((BW + 2) * Z * len(big), (BH + 2) * Z))
    for i, (_, rows) in enumerate(big):
        oy, ox = 1, i * (BW + 2) + 1
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    for d in range(Z * Z): img.putpixel(((ox + x) * Z + d % Z, (oy + y) * Z + d // Z), 1)
    img.save(sys.argv[sys.argv.index('--preview') + 1])
