#!/usr/bin/env python3
"""Regenerate sonic_watch/sonic_sprites.h from assets/sonic_sprite/sonic.txt.

The art file is plain text: a "= name" line starts each frame, then 18 rows of 16 chars
('#' = lit, '.' = dark), Sonic facing right with his feet on the bottom row. Frame order
in the file is the SPR_* enum order. Optional: --preview out.png (needs Pillow).
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'assets', 'sonic_sprite', 'sonic.txt')
OUT = os.path.join(ROOT, 'sonic_watch', 'sonic_sprites.h')
W, H = 16, 18

frames = []
for line in open(ART):
    line = line.rstrip('\n')
    if line.startswith('='):
        frames.append((line[1:].strip(), []))
    elif frames and line.strip():
        frames[-1][1].append(line.strip())
for name, rows in frames:
    if len(rows) != H or any(len(r) != W for r in rows):
        sys.exit('frame %s must be %dx%d' % (name, W, H))

out = ['#pragma once', '#include <Arduino.h>', '',
       '// GENERATED by scripts/gen_sonic_sprite.py from assets/sonic_sprite/sonic.txt — edit the',
       '// art there and rerun. Sonic is 16x18 facing right (mirrored for left), XBM bit order',
       '// (LSB = leftmost pixel). Feet sit on the bottom row; the spin-ball sits one row up.',
       'static const uint8_t SONIC_W = %d;' % W, 'static const uint8_t SONIC_H = %d;' % H,
       'static const uint8_t sonicFrames[%d][%d] PROGMEM = {' % (len(frames), H * 2)]
for name, rows in frames:
    out.append('  { // %s' % name)
    for r in rows:
        v = sum(1 << i for i, c in enumerate(r) if c == '#')
        out.append('    0x%02X, 0x%02X,  // %s' % (v & 255, v >> 8, r.replace('.', ' ').rstrip()))
    out.append('  },')
out.append('};')
out.append('enum : uint8_t {\n  ' + ', '.join('SPR_%s = %d' % (n.upper(), i) for i, (n, _) in enumerate(frames)) + ',\n  SPR_COUNT = %d\n};' % len(frames))
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote %s (%d frames)' % (OUT, len(frames)))

if '--preview' in sys.argv:
    from PIL import Image
    Z = 4
    img = Image.new('1', ((W + 2) * Z * len(frames), (H + 2) * Z))
    for i, (_, rows) in enumerate(frames):
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    for dy in range(Z):
                        for dx in range(Z):
                            img.putpixel(((i * (W + 2) + 1 + x) * Z + dx, (1 + y) * Z + dy), 1)
    img.save(sys.argv[sys.argv.index('--preview') + 1])
