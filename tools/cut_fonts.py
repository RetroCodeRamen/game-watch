#!/usr/bin/env python3
"""Cut the fonts the watch uses out of U8g2's 40 MB u8g2_fonts.c, so the host tests can draw real text.
    python3 cut_fonts.py <path to U8g2 clib> <out.c>"""
import re, sys
clib, out = sys.argv[1], sys.argv[2]
src = open(clib + '/u8g2_fonts.c', encoding='latin-1').read()
names = ['u8g2_font_4x6_tr', 'u8g2_font_5x7_tr', 'u8g2_font_6x10_tr', 'u8g2_font_logisoso20_tn',
         'u8g2_font_logisoso24_tn', 'u8g2_font_ncenB10_tr', 'u8g2_font_ncenB14_tr', 'u8g2_font_ncenB18_tr']
parts = ['// generated by tools/cut_fonts.py', '#include "u8g2.h"']
for n in names:
    m = re.search(r'const uint8_t %s\[\d+\] U8G2_FONT_SECTION\("%s"\) =.*?;\n' % (n, n), src, re.S)
    if not m: sys.exit('font not found: ' + n)
    parts.append(m.group(0))
open(out, 'w', encoding='latin-1').write('\n'.join(parts))
